def _letter_grid(ch: str) -> List[List[bool]]:
    if ch not in GLYPHS:
        raise ValueError(f"character {ch!r} isn't in the English pair font (tokipatch/pairfont.py)")
    top, rows = GLYPHS[ch]
    grid = [[False] * 5 for _ in range(12)]
    for i, row in enumerate(rows):
        for x, px in enumerate(row):
            grid[top + i][x] = px == "#"
    return grid


def render_pair(pair: str) -> bytes:
    """Return the 18-byte 1bpp 12x12 glyph for a 2-character string."""
    left, right = _letter_grid(pair[0]), _letter_grid(pair[1])
    bits = []
    for y in range(12):
        row = left[y] + [False, False] + right[y]
        bits.extend(row)
    out = bytearray(18)
    for i, on in enumerate(bits):
        if on:
            out[i // 8] |= 0x80 >> (i % 8)
    return bytes(out)


def supported(ch: str) -> bool:
    return ch in GLYPHS
